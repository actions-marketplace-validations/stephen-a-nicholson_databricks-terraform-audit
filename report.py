"""Generate a Markdown audit report from findings."""

from collections import Counter
from datetime import datetime, timezone
from pathlib import Path

from checks.models import Finding, Severity


def generate_report(findings: list[Finding], target_dir: Path) -> str:
    """Generate a Markdown audit report from a list of findings."""
    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    severity_counts = Counter(f.severity for f in findings)

    lines: list[str] = []
    lines.append("# Databricks Platform Audit Report")
    lines.append("")
    lines.append(f"**Target**: `{target_dir}`  ")
    lines.append(f"**Date**: {now}  ")
    lines.append(f"**Total findings**: {len(findings)}")
    lines.append("")

    # Summary table
    lines.append("## Summary")
    lines.append("")
    lines.append("| Severity | Count |")
    lines.append("|----------|-------|")
    for sev in Severity:
        count = severity_counts.get(sev, 0)
        emoji = {"CRITICAL": "🔴", "HIGH": "🟠", "MEDIUM": "🟡", "LOW": "🔵"}[sev.value]
        lines.append(f"| {emoji} {sev.value} | {count} |")
    lines.append("")

    if not findings:
        lines.append("✅ No issues found. Your Terraform configuration looks good!")
        return "\n".join(lines)

    # Group by category
    by_category: dict[str, list[Finding]] = {}
    for f in findings:
        by_category.setdefault(f.category.value, []).append(f)

    for category, cat_findings in by_category.items():
        lines.append(f"## {category}")
        lines.append("")

        for i, finding in enumerate(cat_findings, 1):
            severity_badge = f"**{finding.severity.value}**"
            lines.append(f"### {i}. {finding.title}")
            lines.append("")
            lines.append(f"**Severity**: {severity_badge}  ")
            lines.append(f"**File**: `{finding.filepath.name}`  ")
            if finding.resource_address:
                lines.append(f"**Resource**: `{finding.resource_address}`")
            lines.append("")
            lines.append(finding.message)
            lines.append("")

            if finding.suggested_fix:
                lines.append("**Suggested fix**:")
                lines.append("")
                lines.append("```hcl")
                lines.append(finding.suggested_fix)
                lines.append("```")
                lines.append("")

    lines.append("---")
    lines.append(f"*Generated by databricks-platform-ops-agent on {now}*")
    return "\n".join(lines)


def write_report(findings: list[Finding], target_dir: Path, output_path: Path) -> None:
    """Write the audit report to a file."""
    report = generate_report(findings, target_dir)
    output_path.write_text(report)
    print(f"\n📄 Report written to {output_path}")
